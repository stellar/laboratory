#!/usr/bin/env node

/**
 * Generate the Stellar Asset Contract (SAC) spec from the stellar CLI.
 *
 * The SAC is built into the network, so its spec isn't stored on the ledger
 * and RPC can't return it. The stellar CLI gets it from the soroban-sdk it's
 * built with. Re-run this after a protocol or stellar CLI release that changes
 * the SAC interface.
 *
 * Requires the stellar CLI (https://developers.stellar.org/docs/tools/cli).
 */

import { execFileSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const SCRIPT_FILE = "scripts/fetch-sac-spec.mjs";
const OUTPUT_FILE = "src/constants/stellarAssetContractSpec.ts";

// Native asset SAC on testnet. Any SAC returns the same spec.
const SAC_CONTRACT_ID =
  "CDLZFC3SYJYDZT7K67VZ75HPJVIEUVNIXF47ZG2FB2RMQQVU2HHGCYSC";

const stellar = (args) =>
  execFileSync("stellar", args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  }).trim();

const getSpec = (output) =>
  stellar([
    "contract",
    "info",
    "interface",
    "--contract-id",
    SAC_CONTRACT_ID,
    "--network",
    "testnet",
    "--output",
    output,
  ]);

/**
 * Loads the xdr-json wasm from node_modules to encode each spec entry.
 */
const loadXdrJson = async () => {
  const dir = path.join(
    __dirname,
    "..",
    "node_modules/@stellar/stellar-xdr-json",
  );
  const xdrJson = await import(path.join(dir, "stellar_xdr_json.js"));
  xdrJson.initSync(fs.readFileSync(path.join(dir, "stellar_xdr_json_bg.wasm")));
  return xdrJson;
};

const main = async () => {
  let cliVersion;

  try {
    cliVersion = stellar(["--version"]).split("\n")[0];
  } catch {
    console.error(
      "❌ stellar CLI not found. Install it: https://developers.stellar.org/docs/tools/cli",
    );
    process.exit(1);
  }

  console.log(`📦 Using ${cliVersion}`);

  const entries = JSON.parse(getSpec("json"));
  const xdrJson = await loadXdrJson();
  const xdrEntries = entries.map((entry) =>
    xdrJson.encode("ScSpecEntry", JSON.stringify(entry)),
  );

  // The CLI's XDR output is all entries joined into one stream. Matching it
  // confirms each entry was encoded without loss.
  const joined = Buffer.concat(
    xdrEntries.map((xdr) => Buffer.from(xdr, "base64")),
  ).toString("base64");

  if (joined !== getSpec("xdr-base64")) {
    console.error("❌ Encoded entries don’t match the stellar CLI XDR output");
    process.exit(1);
  }

  const lines = entries.map((entry, i) => {
    const [kind] = Object.keys(entry);
    return `  // ${kind} ${entry[kind].name}\n  "${xdrEntries[i]}",`;
  });

  const content = `// This file is auto-generated by ${SCRIPT_FILE}
// DO NOT EDIT MANUALLY
// Generated with ${cliVersion}

/**
 * Stellar Asset Contract spec entries (\`ScSpecEntry\`), as base64 XDR.
 */
export const STELLAR_ASSET_CONTRACT_SPEC: string[] = [
${lines.join("\n")}
];
`;

  fs.writeFileSync(path.join(__dirname, "..", OUTPUT_FILE), content, "utf8");
  console.log(`✅ Wrote ${entries.length} SAC spec entries to ${OUTPUT_FILE}`);
};

main();
